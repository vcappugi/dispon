-- 5. Tabla `bancos`
CREATE TABLE IF NOT EXISTS public.bancos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    nombre TEXT,
    descripcion TEXT
);

ALTER TABLE public.bancos ENABLE ROW LEVEL SECURITY;

-- 6. Tabla `cuentas`
CREATE TABLE IF NOT EXISTS public.cuentas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    banco_id BIGINT REFERENCES public.bancos(id) ON DELETE CASCADE,
    cuenta TEXT,
    tipo TEXT
);

ALTER TABLE public.cuentas ENABLE ROW LEVEL SECURITY;

-- 7. Tabla `saldos_banco`
CREATE TABLE IF NOT EXISTS public.saldos_banco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    banco_id BIGINT REFERENCES public.bancos(id) ON DELETE CASCADE,
    fecha DATE,
    monto NUMERIC(18, 2) DEFAULT 0,
    moneda TEXT
);

ALTER TABLE public.saldos_banco ENABLE ROW LEVEL SECURITY;

-- 8. Tabla `movimientos`
CREATE TABLE IF NOT EXISTS public.movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    banco_id BIGINT REFERENCES public.bancos(id) ON DELETE SET NULL,
    cuenta_id BIGINT REFERENCES public.cuentas(id) ON DELETE SET NULL,
    fecha DATE,
    moneda TEXT,
    empresa TEXT,
    referencia TEXT,
    descripcion TEXT,
    tipo TEXT,
    debe NUMERIC(18, 2) DEFAULT 0,
    haber NUMERIC(18, 2) DEFAULT 0
);

ALTER TABLE public.movimientos ENABLE ROW LEVEL SECURITY;

-- 9. Políticas RLS para las tablas del sistema
DO $$
DECLARE
    t_name TEXT;
BEGIN
    FOREACH t_name IN ARRAY ARRAY['usuarios', 'bancos', 'cuentas', 'saldos_banco', 'movimientos']
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_policies
            WHERE schemaname = 'public'
              AND tablename = t_name
              AND policyname = t_name || '_all_access_policy'
        ) THEN
            EXECUTE format(
                'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);',
                t_name || '_all_access_policy',
                t_name
            );
        END IF;
    END LOOP;
END
$$;

GRANT EXECUTE ON FUNCTION public.desencriptar_texto(TEXT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.encriptar_texto(TEXT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.encrypt_data(TEXT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.decrypt_data(TEXT, TEXT) TO anon, authenticated;

-- 10. Vista `vista_resumen_saldos_movimientos`
-- Totaliza por fecha (`fecha`), banco (`banco_id`) y moneda los saldos bancarios
-- e indicadores directamente desde `public.movimientos` (ignorando `saldos_banco`)
-- respetando las políticas RLS mediante `security_invoker = true`.
CREATE OR REPLACE VIEW public.vista_resumen_saldos_movimientos
WITH (security_invoker = true)
AS
SELECT
    ROW_NUMBER() OVER (ORDER BY m.fecha DESC, m.banco_id ASC, m.moneda ASC) AS id,
    m.banco_id,
    b.nombre AS banco_nombre,
    b.descripcion AS banco_descripcion,
    m.fecha,
    COALESCE(m.moneda, 'VES') AS moneda,
    COUNT(m.id)::BIGINT AS total_movimientos,
    COUNT(m.id) FILTER (WHERE m.cuenta_id IS NOT NULL)::BIGINT AS movimientos_con_cuenta,
    COUNT(m.id) FILTER (WHERE m.cuenta_id IS NULL)::BIGINT AS movimientos_directo_banco,
    COUNT(DISTINCT m.cuenta_id)::BIGINT AS total_cuentas_movidas,
    COALESCE(SUM(m.debe), 0)::NUMERIC(18, 2) AS total_debe,
    COALESCE(SUM(m.haber), 0)::NUMERIC(18, 2) AS total_haber,
    COALESCE(SUM(COALESCE(m.haber, 0) - COALESCE(m.debe, 0)), 0)::NUMERIC(18, 2) AS saldo_disponible,
    MIN(m.fecha) AS primera_fecha,
    MAX(m.fecha) AS ultima_fecha
FROM public.movimientos m
LEFT JOIN public.bancos b ON b.id = m.banco_id
GROUP BY m.fecha, m.banco_id, b.nombre, b.descripcion, m.moneda;

GRANT SELECT ON public.vista_resumen_saldos_movimientos TO anon, authenticated;
